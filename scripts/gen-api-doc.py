#!/usr/bin/env python3
"""Regenerate packages/contracts/openapi.json and docs/api.md from the FastAPI app (contract source of truth)."""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / p) for p in ("apps/host-api", "apps/setup", "packages/contracts", "packages/agent-runtime",
                                        "packages/provider-adapters", "packages/telegram-gateway", "packages/live-broker")]
os.environ.setdefault("NEBULA_SECRET_BACKEND", "memory")
from nebula_host.app import create_app  # noqa: E402
from nebula_host.events import EVENT_TYPES  # noqa: E402

spec = create_app().openapi()
(ROOT / "packages/contracts/openapi.json").write_text(json.dumps(spec, indent=2, sort_keys=True) + "\n")
lines = ["# NEBULA HTTP API", "",
         "Generated by `scripts/gen-api-doc.py` from the running FastAPI app; machine-readable contract: "
         "`packages/contracts/openapi.json` (also served at `/api/openapi.json`, Swagger UI at `/api/docs`).", "",
         "* Success: `{\"data\": …, \"request_id\": \"…\", \"job_id\"?: \"…\"}` · Error: "
         "`{\"error\": {\"code\", \"message\", \"details\"}, \"request_id\"}` with an HTTP status.",
         "* Auth: session cookie `nebula_session` (HttpOnly, SameSite=Strict). Every POST/PUT/PATCH/DELETE needs "
         "`Origin: http://127.0.0.1:<port>` and `x-csrf-token` (from `/api/v1/auth/state`).",
         "* `Idempotency-Key` header is honoured on POST /agents, POST /agents/{id}/tasks, DELETE /agents/{id}, "
         "POST /setup/install.",
         "* Live stream: `POST /api/v1/agents/{id}/live/connect` → `ws://127.0.0.1:<port>/api/v1/live/ws/{session_id}"
         "?token=…` (subprotocol `binary`, raw RFB). Token is single-use and short-lived.", "",
         "| Method | Route | Summary |", "|---|---|---|"]
for path, ops in sorted(spec["paths"].items()):
    for method, op in ops.items():
        lines.append(f"| {method.upper()} | `{path}` | {op.get('summary', '')} |")
lines += ["", "## Event stream (`GET /api/v1/events`, Server-Sent Events)", "",
          "Each event: `{id, sequence, type, agent_id?, task_id?, timestamp, payload}`; resume with `?since=<sequence>`.",
          "", "Types: " + ", ".join(f"`{t}`" for t in sorted(EVENT_TYPES)), ""]
(ROOT / "docs/api.md").write_text("\n".join(lines))
print(f"{len(spec['paths'])} paths")
